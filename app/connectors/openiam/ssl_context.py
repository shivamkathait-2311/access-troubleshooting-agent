# qa422.openiam.com's TLS handshake omits its own intermediate cert (a
# server misconfiguration, confirmed against openssl s_client and curl).
# Windows/macOS silently work around this in Postman because their native
# TLS stacks (SChannel/Secure Transport) do AIA chasing — automatically
# fetching a missing intermediate from the URL the leaf cert points to.
# OpenSSL (what httpx/curl/most Linux deployments use, including this
# app's) does not do that by default, so verification fails with "unable
# to get local issuer certificate" unless we supply the missing link
# ourselves. This is that one intermediate — "Go Daddy Secure Certificate
# Authority - G2" — fetched from the server's own AIA URL
# (http://certificates.godaddy.com/repository/gdig2.crt) and confirmed to
# chain up to "Go Daddy Root Certificate Authority - G2", which is already
# in certifi's trusted root bundle (sha256 fingerprint:
# 97:3A:41:27:6F:FD:01:E0:27:A2:AA:D4:9E:34:C3:78:46:D3:E9:76:FF:6A:62:0B:67:12:E3:38:32:04:1A:A6).
