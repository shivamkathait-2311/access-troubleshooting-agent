def build_ssl_context() -> ssl.SSLContext:
    """certifi's standard root bundle plus the one intermediate some
    OpenIAM deployments (e.g. qa422) fail to send. See the comment above
    _GODADDY_G2_INTERMEDIATE_PEM — this still fully verifies every other
    part of the chain, it just completes the one link the server omits."""
    context = ssl.create_default_context(cafile=certifi.where())
    context.load_verify_locations(cadata=_GODADDY_G2_INTERMEDIATE_PEM)
    return context
